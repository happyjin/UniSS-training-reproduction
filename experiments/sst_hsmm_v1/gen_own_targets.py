"""sst_hsmm_v1 P10 (prereg change 18): the frozen translator's OWN full-audio translations of the training samples
(p4/samples.jsonl, the same 16000 (step, slot) mixtures as P4-P7'), used as the lattice target sequences (self-generated by
the same model; no reference translation, no other model). Prompt = e2e_si_thinker's head with the whole audio, greedy,
max 160 tokens, stop <|im_end|> (= the streaming system's final read). Shard k of n by line index.
    <vllm_omni_030 python> -m experiments.sst_hsmm_v1.gen_own_targets --thinker <merged> --shard k --num-shards n --out <jsonl>
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import soundfile as sf

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
QWEN3 = str(REPO / "pretrained_models/Qwen3-Omni-30B-A3B-Instruct")
THINKER_EOS = 151645


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--thinker", required=True)
    ap.add_argument("--samples", default=str(REPO / "eval_outputs/sst_hsmm_v1/p4/samples.jsonl"))
    ap.add_argument("--shard", type=int, required=True)
    ap.add_argument("--num-shards", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--gpu-mem", type=float, default=0.5)
    a = ap.parse_args()
    if Path(a.out).exists():
        raise SystemExit(f"拒绝覆盖已有输出: {a.out}")
    from transformers import Qwen3OmniMoeProcessor
    from vllm import LLM, SamplingParams
    from experiments.uniss_qwen3_omni_v1.training.e2_batch import inference_instruction
    rows = [json.loads(l) for i, l in enumerate(open(a.samples, encoding="utf-8")) if l.strip() and i % a.num_shards == a.shard]
    proc = Qwen3OmniMoeProcessor.from_pretrained(QWEN3)
    head = {}
    for d, tgt in (("en2zh", "cmn"), ("zh2en", "eng")):
        conv = [{"role": "user", "content": [{"type": "audio", "audio": "x.wav"}, {"type": "text", "text": inference_instruction()[tgt]}]}]
        head[d] = proc.apply_chat_template([conv], add_generation_prompt=True, tokenize=False)[0]
    llm = LLM(model=a.thinker, gpu_memory_utilization=a.gpu_mem, max_model_len=8192, limit_mm_per_prompt={"audio": 1},
              seed=20261124, tensor_parallel_size=1)
    prompts = []
    for r in rows:
        x, sr = sf.read(str(REPO / r["wav"]), dtype="float32", always_2d=True)
        assert sr == 16000, r["wav"]
        prompts.append({"prompt": head[r["dir"]], "multi_modal_data": {"audio": (x.mean(axis=1), 16000)}})
    sp = SamplingParams(temperature=0.0, max_tokens=160, stop_token_ids=[THINKER_EOS])
    res = llm.generate(prompts, sp, use_tqdm=False)
    with open(a.out + ".tmp", "x", encoding="utf-8") as fh:
        for r, o in zip(rows, res):
            fh.write(json.dumps({"key": f"s{r['s']:04d}_j{r['j']:02d}", "dir": r["dir"], "translation": o.outputs[0].text.strip()},
                                ensure_ascii=False) + "\n")
    Path(a.out + ".tmp").rename(a.out)
    print("done", len(rows), flush=True)


if __name__ == "__main__":
    main()
