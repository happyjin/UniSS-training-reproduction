"""Paper v11 tables, macros and switches (docs/mist_v11_plan.zh-CN.md, plan A: MIST = deadline Thinker + playback
layer, write alignment = analysis). Run after make_tables_v10.py; reads generated/macros_v10.tex and the v10 tables and
the v11 result files when they exist; writes only into paper/gstar_si_v11/generated:

  macros_v11.tex       derived numbers (absolute values for the abstract) and v11 result macros
  switches_v11.tex     \\Factorialtrue etc. for every v11 result that exists
  tab_v11_main.tex     tab_v10_main with the v11 system names (B+PA is MIST; the write-aligned row is MIST+WA)

    python scripts/make_tables_v11.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
GEN = PAPER / "generated"
ROOT = PAPER.parents[1]
V11 = ROOT / "eval_outputs/mist_w3po_v1/v11_paper"   # one JSON per v11 result, written by the result reports' tools

MAC = {}
for m in re.finditer(r"\\csname n@(.+?)\\endcsname\{(.*)\}$", (GEN / "macros_v10.tex").read_text(), re.M):
    MAC[m.group(1)] = m.group(2)

out: dict[str, str] = {}


def absval(key: str) -> None:
    v = MAC[key]
    out[key + "abs"] = v.replace("$-$", "").replace("+", "")


for s in ("ami", "en", "ali"):
    for k in ("bslaal", "endoff", "spread", "startoff"):
        absval(f"v10:pr:test:{s}:e2-b:{k}:diff")

# v11 results: each file is {"switch": "Factorial", "macros": {key: value}}; present -> switch on
WIDE = {"wallclock", "factorial", "fluencypa"}
switches = {k: False for k in ("Factorial", "FluencyPA", "AliEval", "Wallclock", "WAcurve", "SfourK", "MetricsV")}
if V11.exists():
    for f in sorted(V11.glob("*.json")):
        d = json.loads(f.read_text())
        if d.get("final"):
            switches[d["switch"]] = True
            out.update({k: str(v) for k, v in d.get("macros", {}).items()})
            if d.get("table"):   # a ready LaTeX table -> generated/tab_v11_<stem>.tex
                tab = d["table"]
                if f.stem in WIDE:   # wider than one column -> both columns
                    tab = tab.replace("\\begin{table}", "\\begin{table*}").replace("\\end{table}", "\\end{table*}")
                (GEN / f"tab_v11_{f.stem}.tex").write_text(tab)

# P0-3: the deadline Thinker under the same decoding bias family (dev5 text) next to write alignment's calibration points
WB = ROOT / "logs/mist_w3po_v1/joint/wb"
if (WB / "summary_base.tsv").exists():
    base = {}
    for l in (WB / "summary.tsv").read_text().splitlines()[1:] + (WB / "summary_base.tsv").read_text().splitlines()[1:]:
        f = l.split("\t")
        if "_dev5_base" in f[0]:
            base[f[0]] = (float(f[4]), float(f[1]))
    panels = []
    for d, title in (("z", "Zh$\\rightarrow$En"), ("e", "En$\\rightarrow$Zh")):
        b = sorted(v for k, v in base.items() if k.startswith(f"wb{d}_"))
        w = sorted((float(MAC[f"v10:cal:{d}:{m}:laal"]), float(MAC[f"v10:cal:{d}:{m}:bleu"])) for m in ("m0", "m1", "m2", "m3"))
        dl = base[f"wb{d}_dev5_base_s6000"]
        pts = lambda xs: " ".join(f"({x:.3f},{y:.2f})" for x, y in xs)
        panels.append(
            "\\begin{tikzpicture}\\begin{axis}[width=0.52\\columnwidth,height=3.3cm,xlabel={text LAAL (s)},ylabel={tcpBLEU},"
            f"title={{{title}}},\ntitle style={{font=\\small}},label style={{font=\\scriptsize}},tick label style={{font=\\scriptsize}},"
            "legend style={font=\\tiny,at={(0.98,0.02)},anchor=south east}]\n"
            f"\\addplot[solid,mark=*,mark size=1.2pt,frozen] coordinates {{{pts(b)}}}; \\addlegendentry{{B, $\\bias\\in[-2,1]$}}\n"
            f"\\addplot[dashed,mark=square*,mark size=1.2pt,trained] coordinates {{{pts(w)}}}; \\addlegendentry{{+WA, $\\bias\\in[-3,0]$}}\n"
            f"\\addplot[only marks,mark=o,mark size=2.4pt] coordinates {{{pts([dl])}}};\n"
            "\\end{axis}\\end{tikzpicture}")
    (GEN / "fig_v11_wacurve.tex").write_text(
        "\\begin{figure}[t]\n\\centering\n" + "\n".join(panels) + "\n\\caption{Text quality against text lag on five "
        "development meetings when a constant bias $\\bias$ is added to the wait logit, for the deadline Thinker (B) and for "
        "the write-aligned Thinker (+WA, stage 2). Circle: B without bias. The write-aligned points lie on or below the "
        "deadline curve.}\n\\label{fig:wacurve}\n\\end{figure}\n")

with open(GEN / "macros_v11.tex", "w") as fh:
    fh.write("% generated by scripts/make_tables_v11.py\n")
    for k, v in sorted(out.items()):
        fh.write(f"\\expandafter\\def\\csname n@{k}\\endcsname{{{v}}}\n")
with open(GEN / "switches_v11.tex", "w") as fh:
    fh.write("% generated by scripts/make_tables_v11.py\n")
    for k, on in switches.items():
        fh.write(f"\\{k}{'true' if on else 'false'}\n")

t = (GEN / "tab_v10_main.tex").read_text()
for a, b in [("B + playback alignment (B+PA)", "\\sys{}: B + playback alignment"),
             ("\\sys{}: B+PA + write alignment, $\\bias=-1$", "\\sys{}+WA, $\\bias=-1$ (\\S\\ref{sec:write})"),
             ("Italic: the first test decoding, before $\\bias$ was introduced (\\S\\ref{sec:res-hygiene}).",
              "Italic: the first test decoding of \\sys{}+WA, before $\\bias$ was introduced (\\S\\ref{sec:write})."),
             ("each system decoded once (systems: \\S\\ref{sec:setup})",
              "each system decoded once (systems: \\S\\ref{sec:setup}); B and \\sys{} share their text")]:
    assert a in t, a
    t = t.replace(a, b)
# the first (delta = 0) test decodings of MIST+WA are in the appendix (Table tab:delta0), not in the main table
t = "\n".join(l for l in t.split("\n") if "first test run" not in l).replace("\\multirow{4}", "\\multirow{3}")
a = ("Italic: the first test decoding of \\sys{}+WA, before $\\bias$ was introduced (\\S\\ref{sec:write}).",
     "The first test decoding of \\sys{}+WA, before $\\bias$ was introduced, is in Table~\\ref{tab:delta0}.")
assert a[0] in t
t = t.replace(*a)
a = ("Latency per speaker stream, chunk protocol, computation not counted; speech start: first heard word of a unit; "
     "LAAL$_\\text{block}$: conventional block-start speech LAAL (\\S\\ref{sec:setup}).",
     "Latency (\\S\\ref{sec:setup}): per speaker stream, chunk protocol, computation not counted.")
assert a[0] in t, a[0]
t = t.replace(*a)
# one caption, shorter than v10's (page budget); metric definitions are in the setup section
t = re.sub(r"\\caption\{Whole test meetings.*\}\n", lambda m: (
    "\\caption{Whole test meetings, run online, each system decoded once (\\S\\ref{sec:setup}); B and \\sys{} share "
    "their text; the first test decoding of \\sys{}+WA (before $\\bias$) is in Table~\\ref{tab:delta0}. tcpBLEU: all / "
    "overlapped / single-speaker units; ASR-BLEU: mean of two TTS seeds; latency: per speaker stream, chunk protocol, "
    "without computation. Against B (Table~\\ref{tab:sig10}): $^{*}$ $p_\\text{Holm}<0.05$, $^{\\circ}$ not "
    "significant; latency intervals: Table~\\ref{tab:postreview2}.}\n"), t, count=1)
assert "latency intervals: Table" in t
(GEN / "tab_v11_main.tex").write_text(t)

# appendix tables carried over from v10: v10's MIST (write-aligned) is v11's MIST+WA; v10's B+PA is v11's MIST
for f in ("e7", "ablation", "sig", "postreview", "decomp", "m2laal"):
    u = (GEN / f"tab_v10_{f}.tex").read_text()
    u = re.sub(r"\\sys\{\}(?!-Simul| \(offline\)|\+WA)", "@@WA@@", u).replace("B+PA", "\\sys{}").replace("@@WA@@", "\\sys{}+WA")
    (GEN / f"tab_v11_{f}.tex").write_text(u)
print("switches:", {k: v for k, v in switches.items() if v} or "none", "| macros:", len(out))
